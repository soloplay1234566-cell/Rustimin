import {test,expect} from '@playwright/test'
import path from 'node:path'
test('bundled audio plays, seeks, pauses and moves to next track',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/');await expect(page.getByRole('heading',{name:'Поймай свой вайб.'})).toBeVisible()
 await page.getByRole('button',{name:'Воспроизвести',exact:true}).click()
 await expect(page.getByRole('button',{name:'Пауза',exact:true})).toBeVisible()
 await expect.poll(()=>page.locator('audio').evaluate((e:HTMLAudioElement)=>e.currentTime)).toBeGreaterThan(.2)
 await page.getByRole('slider',{name:'Позиция воспроизведения'}).fill('25')
 await expect.poll(()=>page.locator('audio').evaluate((e:HTMLAudioElement)=>e.currentTime)).toBeGreaterThan(24)
 await page.getByRole('button',{name:'Пауза',exact:true}).click()
 await expect.poll(()=>page.locator('audio').evaluate((e:HTMLAudioElement)=>e.paused)).toBe(true)
 await page.getByRole('button',{name:'Следующий трек',exact:true}).click()
 await expect(page.locator('.player-track strong')).toHaveText('Невесомость')
 expect(errors).toEqual([])
})
test('local file and LRC survive reload; favorites and deletion work',async({page})=>{
 await page.goto('/');await page.waitForTimeout(250)
 await page.locator('input[type=file][multiple]').setInputFiles({name:'Исполнитель - Тестовая песня.mp3',mimeType:'audio/mpeg',buffer:await import('node:fs/promises').then(fs=>fs.readFile(path.resolve('public/audio/night.mp3')))})
 await expect(page.getByRole('status')).toContainText('Добавлено треков: 1')
 await page.getByRole('button',{name:'Моя медиатека',exact:true}).click()
 await page.getByRole('button',{name:'Включить Тестовая песня',exact:true}).click()
 await expect(page.locator('.player-track strong')).toHaveText('Тестовая песня')
 await expect.poll(()=>page.locator('audio').evaluate((e:HTMLAudioElement)=>e.currentTime)).toBeGreaterThan(.1)
 await page.getByRole('button',{name:'Избранное: Тестовая песня',exact:true}).click()
 await page.locator('input[accept=".lrc"]').setInputFiles({name:'lyrics.lrc',mimeType:'text/plain',buffer:Buffer.from('[00:00.00]Первая строка\n[00:20.00]Вторая строка')})
 await expect(page.getByRole('status')).toContainText('Текст песни добавлен')
 await page.reload();await page.waitForTimeout(300)
 await page.getByRole('button',{name:/^Избранное/}).first().click()
 await expect(page.getByRole('button',{name:'Включить Тестовая песня'})).toBeVisible()
 await page.getByRole('button',{name:'Включить Тестовая песня'}).click()
 await page.getByRole('button',{name:'Сейчас играет',exact:true}).click()
 await expect(page.getByRole('button',{name:'Первая строка',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Вторая строка',exact:true}).click()
 await expect.poll(()=>page.locator('audio').evaluate((e:HTMLAudioElement)=>e.currentTime)).toBeGreaterThan(19)
 await page.getByRole('button',{name:'Моя медиатека',exact:true}).click()
 await page.getByRole('button',{name:'Удалить Тестовая песня',exact:true}).click()
 await expect(page.getByRole('button',{name:'Включить Тестовая песня'})).toHaveCount(0)
})
test('radio country and search select real API parameters; stream can play',async({page})=>{
 const requests:string[]=[]
 await page.route('https://*.api.radio-browser.info/**',async route=>{requests.push(route.request().url());await route.fulfill({json:[{stationuuid:'test-radio',name:'Test Radio',url_resolved:'http://127.0.0.1:5173/audio/night.mp3',countrycode:'US',tags:'chill,ambient',codec:'MP3'}]})})
 await page.goto('/');await page.getByRole('button',{name:'Музыка мира',exact:true}).click()
 await page.getByRole('button',{name:'🇺🇸 США',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Test Radio'})).toBeVisible()
 expect(requests.some(u=>u.includes('countrycode=US'))).toBe(true)
 await page.getByRole('button',{name:'Слушать Test Radio'}).click()
 await expect.poll(()=>page.locator('audio').evaluate((e:HTMLAudioElement)=>e.currentTime)).toBeGreaterThan(.1)
 await expect(page.getByRole('slider',{name:'Позиция воспроизведения'})).toBeDisabled()
 await page.getByRole('textbox',{name:'Поиск музыки'}).fill('Jazz')
 await expect.poll(()=>requests.some(u=>u.includes('name=Jazz'))).toBe(true)
})
test('radio failure has recovery and custom stations persist',async({page})=>{
 await page.route('https://*.api.radio-browser.info/**',route=>route.abort())
 await page.goto('/');await page.getByRole('button',{name:'Музыка мира',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Не удалось поймать сигнал'})).toBeVisible()
 await page.getByRole('button',{name:'Свой поток'}).click()
 await page.getByRole('textbox',{name:'Название',exact:true}).fill('Мой эфир')
 await page.getByRole('textbox',{name:'Ссылка на поток'}).fill('http://127.0.0.1:5173/audio/night.mp3')
 await page.getByRole('button',{name:'Добавить станцию',exact:true}).click()
 await page.reload();await page.getByRole('button',{name:'Музыка мира',exact:true}).click()
 await expect(page.getByRole('button',{name:'Включить Мой эфир'})).toBeVisible()
})
